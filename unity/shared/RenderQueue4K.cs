using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

// Course Flyover > Render 4K Queue
// Offline, deterministic frame rendering of the cinematic flyover clips (CommercialFlyoverPath) at 3840x2160 / 60 fps PNG.
// No Unity Recorder dependency (the base project is Unity 2018.2): each frame samples the AnimationClip at an exact time with
// AnimationMode.SampleAnimationClip, renders a dedicated camera to a render target, and writes the PNG. Nothing depends on the
// real-time clock; physics auto-simulation is off during the pass, so no frame can drop or skip.
//  - Anti-aliasing: MSAA render_4k.msaa on the target, plus supersample render_4k.supersample (target = size * factor, clamped to the GPU
//    max texture size, bilinear downsample to 4K).
//  - Motion blur: a 180 deg shutter done the offline way: render_4k.motion_blur.subframes (8) sub-frames spread over shutter/360 of the frame
//    interval, averaged. PPv2 MotionBlur is switched off for the pass so it is not applied twice (restored after).
//  - Max quality for the pass (restored after): shadow distance, cascades, LOD bias, every LODGroup forced to LOD 0 (SpeedTree billboards
//    never trigger), terrain tree/detail/basemap distances, texture limit 0, anisotropic forced.
//  - Queue: holes "1-18" or "10" (static field or bridge -Set); the clip Assets/CourseBuild/flyovers/H<NN>_cinematic.anim is generated by
//    CommercialFlyoverPath if missing; frames go to AutomationOutput/renders_4k/Hole_XX/frame_00000.png.
//  - Disk guard: before each hole the drive's free space must cover the hole's estimate (max of frames*12 MB and 18 GB) AND stay above the
//    25 GB floor (render_4k.disk.min_free_gb); otherwise the queue HALTS with DISK_SPACE_EXCEEDED, logged, no further holes.
//  - Log: AutomationOutput/logs/render_queue_<stamp>.json: per hole frames, seconds, folder, duration, status; totals.
// Menu: Course Flyover > Render 4K Queue.  Bridge: invoke -Tool RenderQueue4K -Method RunRenderQueue -Set @{ holes = "10" }
// Editor only: post-processing does not run in batch mode. Expect ~1,500 frames and ~18 GB per 25 s hole.
// NOT YET COMPILED ON THE PC (written in the cloud 2026-11-03).
public class RenderQueue4K : EditorWindow
{
    [Serializable] public class MotionBlur { public float shutter_deg = 180; public int subframes = 4; }
    [Serializable] public class Quality { public float shadow_distance_m = 5000, lod_bias = 10, tree_distance_m = 5000, detail_distance_m = 2000, basemap_distance_m = 5000; public int shadow_cascades = 4, texture_limit = 0; public bool force_lod0_on_lodgroups = true; }
    [Serializable] public class Disk { public float png_estimate_mb = 12, hole_estimate_gb = 18, min_free_gb = 25; }
    [Serializable] public class R4K { public int width = 3840, height = 2160, fps = 60, msaa = 8; public float supersample = 1.5f; public MotionBlur motion_blur = new MotionBlur(); public Quality quality = new Quality(); public Disk disk = new Disk(); }
    [Serializable] public class FlyRules { public R4K render_4k = new R4K(); }

    const string CB = "Assets/CourseBuild";
    static readonly CultureInfo CI = CultureInfo.InvariantCulture;
    public static string holes = "1-18"; public static bool dryRun = false;
    string last = ""; Vector2 scroll;

    [MenuItem("Course Flyover/Render 4K Queue")]
    static void Open() { GetWindow<RenderQueue4K>("Render 4K"); }
    void OnGUI()
    {
        holes = EditorGUILayout.TextField("Holes (1-18 or 10)", holes); dryRun = EditorGUILayout.Toggle("Dry run (count frames, check disk)", dryRun);
        if (GUILayout.Button(dryRun ? "Estimate" : "RENDER")) last = RunRenderQueue();
        scroll = EditorGUILayout.BeginScrollView(scroll); EditorGUILayout.TextArea(last); EditorGUILayout.EndScrollView();
    }

    static string ProjectDir() { return Path.GetDirectoryName(Application.dataPath).Replace('\\', '/'); }
    static T LoadJson<T>(string p, T fb) where T : class { return File.Exists(p) ? JsonUtility.FromJson<T>(File.ReadAllText(p).TrimStart('\uFEFF')) : fb; }
    static List<int> ParseHoles(string s) { var o = new List<int>(); foreach (var part in (s ?? "").Split(',')) { var p = part.Trim(); if (p.Length == 0) continue; if (p.Contains("-")) { var ab = p.Split('-'); int a = int.Parse(ab[0]), b = int.Parse(ab[1]); for (int i = a; i <= b; i++) o.Add(i); } else o.Add(int.Parse(p)); } return o; }

    // ---- quality snapshot / override / restore ----
    class Snap { public float shadowDistance, lodBias; public int cascades, texLimit; public AnisotropicFiltering aniso; public bool physics; public List<KeyValuePair<Terrain, float[]>> terrains = new List<KeyValuePair<Terrain, float[]>>(); public List<LODGroup> forced = new List<LODGroup>(); public List<KeyValuePair<object, bool>> ppMotionBlur = new List<KeyValuePair<object, bool>>(); }
    static Snap Override(Quality q)
    {
        var s = new Snap { shadowDistance = QualitySettings.shadowDistance, lodBias = QualitySettings.lodBias, cascades = QualitySettings.shadowCascades, texLimit = QualitySettings.masterTextureLimit, aniso = QualitySettings.anisotropicFiltering, physics = Physics.autoSimulation };
        QualitySettings.shadowDistance = q.shadow_distance_m; QualitySettings.shadowCascades = q.shadow_cascades; QualitySettings.lodBias = q.lod_bias; QualitySettings.masterTextureLimit = q.texture_limit; QualitySettings.anisotropicFiltering = AnisotropicFiltering.ForceEnable; QualitySettings.shadows = ShadowQuality.All; QualitySettings.shadowResolution = ShadowResolution.VeryHigh;
        Physics.autoSimulation = false;
        foreach (var t in Terrain.activeTerrains) { s.terrains.Add(new KeyValuePair<Terrain, float[]>(t, new[] { t.treeDistance, t.detailObjectDistance, t.basemapDistance, t.treeBillboardDistance, t.heightmapPixelError })); t.treeDistance = q.tree_distance_m; t.detailObjectDistance = q.detail_distance_m; t.basemapDistance = q.basemap_distance_m; t.treeBillboardDistance = q.tree_distance_m; t.heightmapPixelError = 1; }
        if (q.force_lod0_on_lodgroups) foreach (var lg in UnityEngine.Object.FindObjectsOfType<LODGroup>()) { lg.ForceLOD(0); s.forced.Add(lg); }
        // PPv2 MotionBlur off for the pass (accumulation does the blur)
        var volT = AppDomain.CurrentDomain.GetAssemblies().Select(a => a.GetType("UnityEngine.Rendering.PostProcessing.PostProcessVolume")).FirstOrDefault(t => t != null);
        if (volT != null) foreach (var v in UnityEngine.Object.FindObjectsOfType(volT))
        {
            var prof = volT.GetField("sharedProfile").GetValue(v); if (prof == null) continue; var list = prof.GetType().GetField("settings").GetValue(prof) as System.Collections.IList; if (list == null) continue;
            foreach (var st in list) if (st.GetType().Name == "MotionBlur") { var act = st.GetType().GetField("active"); if (act != null) { s.ppMotionBlur.Add(new KeyValuePair<object, bool>(st, (bool)act.GetValue(st))); act.SetValue(st, false); } }
        }
        return s;
    }
    static void Restore(Snap s)
    {
        QualitySettings.shadowDistance = s.shadowDistance; QualitySettings.lodBias = s.lodBias; QualitySettings.shadowCascades = s.cascades; QualitySettings.masterTextureLimit = s.texLimit; QualitySettings.anisotropicFiltering = s.aniso; Physics.autoSimulation = s.physics;
        foreach (var kv in s.terrains) { var t = kv.Key; if (!t) continue; t.treeDistance = kv.Value[0]; t.detailObjectDistance = kv.Value[1]; t.basemapDistance = kv.Value[2]; t.treeBillboardDistance = kv.Value[3]; t.heightmapPixelError = kv.Value[4]; }
        foreach (var lg in s.forced) if (lg) lg.ForceLOD(-1);
        foreach (var kv in s.ppMotionBlur) { var act = kv.Key.GetType().GetField("active"); if (act != null) act.SetValue(kv.Key, kv.Value); }
    }

    // ---- one hole ----
    static long bytesWritten = 0;
    static string RenderHole(int hole, R4K R, List<string> log, out int frames, out double seconds, out string folder, bool estimateOnly)
    {
        frames = 0; seconds = 0; folder = ProjectDir() + "/AutomationOutput/renders_4k/Hole_" + hole.ToString("00");
        var clipPath = CB + "/flyovers/H" + hole.ToString("00") + "_cinematic.anim"; var clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(clipPath);
        if (!clip)
        {
            log.Add("hole " + hole + ": no clip at " + clipPath + ", generating with CommercialFlyoverPath"); CommercialFlyoverPath.hole = hole; CommercialFlyoverPath.RunPathGeneration();
            clip = AssetDatabase.LoadAssetAtPath<AnimationClip>(clipPath); if (!clip) return "no clip";
        }
        frames = Mathf.CeilToInt(clip.length * R.fps); seconds = clip.length;
        double needGb = Math.Max(frames * R.disk.png_estimate_mb / 1024.0, R.disk.hole_estimate_gb); double freeGb = double.NaN;
        try { var di = new DriveInfo(Path.GetPathRoot(Path.GetFullPath(folder))); freeGb = di.AvailableFreeSpace / 1024.0 / 1024.0 / 1024.0; } catch { }
        if (!double.IsNaN(freeGb) && (freeGb < R.disk.min_free_gb || freeGb - needGb < R.disk.min_free_gb))
            return string.Format(CI, "DISK_SPACE_EXCEEDED: {0:F1} GB free on {1}, {2:F1} GB needed for {3} frames plus the {4} GB floor; queue halted", freeGb, Path.GetPathRoot(Path.GetFullPath(folder)), needGb, frames, R.disk.min_free_gb);
        if (estimateOnly) return string.Format(CI, "estimate: {0} frames, {1:F1} s, ~{2:F1} GB", frames, seconds, frames * R.disk.png_estimate_mb / 1024.0);
        Directory.CreateDirectory(folder);
        // dedicated camera: a copy of the Main Camera (keeps its PostProcessLayer and settings), driven by the clip
        var main = Camera.main; if (!main) return "no Main Camera to copy (tag MainCamera)";
        var go = UnityEngine.Object.Instantiate(main.gameObject); go.name = "Render4K_Camera"; go.transform.SetParent(null); foreach (var al in go.GetComponentsInChildren<AudioListener>()) UnityEngine.Object.DestroyImmediate(al);
        var cam = go.GetComponent<Camera>(); cam.enabled = false; cam.allowMSAA = true;
        int sw = Mathf.Min(SystemInfo.maxTextureSize, Mathf.RoundToInt(R.width * R.supersample)), sh = Mathf.Min(SystemInfo.maxTextureSize, Mathf.RoundToInt(R.height * R.supersample));
        var big = new RenderTexture(sw, sh, 24, RenderTextureFormat.ARGB32); big.antiAliasing = Mathf.Clamp(R.msaa, 1, 8); big.Create();
        var acc = new RenderTexture(R.width, R.height, 0, RenderTextureFormat.ARGBFloat); var acc2 = new RenderTexture(R.width, R.height, 0, RenderTextureFormat.ARGBFloat); var tmp = new RenderTexture(R.width, R.height, 0, RenderTextureFormat.ARGBFloat);
        var accShader = Shader.Find("Hidden/CourseBuild/Accumulate"); if (!accShader) return "shader Hidden/CourseBuild/Accumulate missing: copy unity/shared/Accumulate.shader into Assets/Editor/Resources (or anywhere in Assets)";
        var accMat = new Material(accShader); var tex = new Texture2D(R.width, R.height, TextureFormat.RGB24, false);
        int sub = Mathf.Max(1, R.motion_blur.subframes); float shutter = Mathf.Clamp(R.motion_blur.shutter_deg, 0, 360) / 360f; float dt = 1f / R.fps;
        var started = DateTime.Now;
        try
        {
            UnityEditor.AnimationMode.StartAnimationMode();
            for (int f = 0; f < frames; f++)
            {
                // accumulate sub-frames across the open shutter, then average: a true 180 deg shutter blur, deterministic
                for (int k = 0; k < sub; k++)
                {
                    float t = f * dt + (sub > 1 ? shutter * dt * k / (sub - 1) : 0f);
                    UnityEditor.AnimationMode.SampleAnimationClip(go, clip, Mathf.Min(t, clip.length));
                    cam.targetTexture = big; cam.Render(); cam.targetTexture = null;
                    if (k == 0) Graphics.Blit(big, acc);
                    else { Graphics.Blit(big, tmp); accMat.SetFloat("_Lerp", 1f / (k + 1)); accMat.SetTexture("_NewTex", tmp); Graphics.Blit(acc, acc2, accMat); var sw2 = acc; acc = acc2; acc2 = sw2; }   // acc = lerp(acc, new, 1/(k+1)) = running mean
                }
                var pa = RenderTexture.active; RenderTexture.active = acc; tex.ReadPixels(new Rect(0, 0, R.width, R.height), 0, 0); tex.Apply(); RenderTexture.active = pa;
                var png = ImageConversion.EncodeToPNG(tex); File.WriteAllBytes(folder + "/frame_" + f.ToString("00000") + ".png", png); bytesWritten += png.LongLength;
                if (f % 60 == 0) { if (EditorUtility.DisplayCancelableProgressBar("Render 4K hole " + hole, "frame " + f + " / " + frames, f / (float)frames)) { log.Add("hole " + hole + ": cancelled at frame " + f); break; } }
            }
        }
        finally
        {
            UnityEditor.AnimationMode.StopAnimationMode(); EditorUtility.ClearProgressBar();
            UnityEngine.Object.DestroyImmediate(go); big.Release(); acc.Release(); acc2.Release(); tmp.Release(); UnityEngine.Object.DestroyImmediate(tex); UnityEngine.Object.DestroyImmediate(accMat);
        }
        return string.Format(CI, "rendered {0} frames in {1:F0} s -> {2}", frames, (DateTime.Now - started).TotalSeconds, folder);
    }

    public static string RunRenderQueue()
    {
        var R = LoadJson(CB + "/rules/flyovers.json", new FlyRules()).render_4k; var list = ParseHoles(holes); if (list.Count == 0) return "no holes parsed from '" + holes + "'";
        string stamp = DateTime.Now.ToString("yyyyMMdd_HHmmss"); string logDir = ProjectDir() + "/AutomationOutput/logs"; Directory.CreateDirectory(logDir);
        var log = new List<string> { "render queue " + stamp + ": holes " + holes + ", " + R.width + "x" + R.height + " @ " + R.fps + " fps, MSAA " + R.msaa + " x SS " + R.supersample.ToString(CI) + ", shutter " + R.motion_blur.shutter_deg.ToString(CI) + " deg / " + R.motion_blur.subframes + " subframes" + (dryRun ? " [DRY RUN]" : "") };
        var items = new List<string>(); int totalFrames = 0; bool halted = false; bytesWritten = 0; var t0 = DateTime.Now; Snap snap = null;
        if (!dryRun) snap = Override(R.quality);
        try
        {
            foreach (var h in list)
            {
                int frames; double secs; string folder; var ht = DateTime.Now;
                long before = bytesWritten; string status = RenderHole(h, R, log, out frames, out secs, out folder, dryRun);
                double dur = (DateTime.Now - ht).TotalSeconds; bool ok = status.StartsWith("rendered") || status.StartsWith("estimate");
                if (ok && !dryRun) totalFrames += frames;
                log.Add("hole " + h + ": " + status);
                items.Add(string.Format(CI, "{{\"hole\":{0},\"frames\":{1},\"seconds\":{2:F2},\"folder\":\"{3}\",\"render_s\":{4:F1},\"bytes\":{5},\"status\":\"{6}\"}}", h, frames, secs, folder.Replace("\"", "'"), dur, bytesWritten - before, status.Replace("\"", "'")));
                if (status.StartsWith("DISK_SPACE_EXCEEDED")) { log.Add("queue halted: DISK_SPACE_EXCEEDED before hole " + h); halted = true; break; }
            }
        }
        finally { if (snap != null) Restore(snap); }
        double total = (DateTime.Now - t0).TotalSeconds;
        var json = "{" + string.Format(CI, "\"stamp\":\"{0}\",\"holes\":\"{1}\",\"dry_run\":{2},\"width\":{3},\"height\":{4},\"fps\":{5},\"subframes\":{6},\"total_frames\":{7},\"bytes_written\":{8},\"gb_written\":{9:F2},\"total_seconds\":{10:F1},\"halted\":{11},\"items\":[{12}]", stamp, holes, dryRun ? "true" : "false", R.width, R.height, R.fps, R.motion_blur.subframes, totalFrames, bytesWritten, bytesWritten / 1073741824.0, total, halted ? "\"DISK_SPACE_EXCEEDED\"" : "false", string.Join(",", items.ToArray())) + "}";
        File.WriteAllText(logDir + "/render_queue_" + stamp + ".json", json);
        log.Add(string.Format(CI, "total {0} frames, {1:F2} GB written, {2:F0} s{3} -> {4}/render_queue_{5}.json", totalFrames, bytesWritten / 1073741824.0, total, halted ? " (HALTED: DISK_SPACE_EXCEEDED)" : "", logDir, stamp));
        var txt = string.Join("\n", log.ToArray()); Debug.Log("RenderQueue4K:\n" + txt); return txt;
    }
}
